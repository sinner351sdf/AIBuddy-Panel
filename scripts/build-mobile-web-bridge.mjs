// The mobile HTTP bridge is generated from the server's canonical web shim.
// No new native commands or credential store are introduced.
import fs from 'node:fs'
const root = new URL('../', import.meta.url)
const source = fs.readFileSync(new URL('desktop-tauri/src-tauri/server/src/web_shim.rs', root), 'utf8')
const js = source.split('pub fn shim_js()')[1]?.match(/r#"([\s\S]*?)"#/u)?.[1]
if (!js?.includes("platform: 'web'")) throw new Error('Canonical HTTP bridge not found')
fs.writeFileSync(new URL('desktop-tauri/ui/m-feature-bridge.js', root), '// Generated by scripts/build-mobile-web-bridge.mjs; do not edit.\n' + js.trimEnd() + '\n')
